package com.example.demo4.testObj1;

public class BuffTest {
    public int a;
    public int b;
    public int c;

    public BuffTest(int a, int b, int c) {
        this.a = a;
        this.b = b;
        this.c = c;
    }

    @Override
    public String toString() {
        return "BuffTest{" +
                "a=" + a +
                ", b=" + b +
                ", c=" + c +
                '}';
    }
}
